export function toTraditionalChinese(text: string | undefined | null): string {
  if (!text || typeof text !== 'string') return (text as string) || '';

  let result = text;
  for (const [s, t] of Object.entries(S2T_DICT)) {
    if (result.includes(s)) {
      result = result.replaceAll(s, t);
    }
  }

  let converted = '';
  for (let i = 0; i < result.length; i++) {
    converted += CHAR_MAP[result[i]] || result[i];
  }
  return converted;
}
